'use strict';
const assert=require('node:assert/strict');
const countdown=require('../public/assets/countdowns.js');
const events=[{id:'gta',ends_at:100,enabled:true,images:['/assets/countdowns/gta-01.jpg','/assets/countdowns/gta-02.jpg','/assets/countdowns/gta-03.jpg']},{id:'doomsday',ends_at:200,enabled:true}];
const data={countdowns:events};
assert.equal(countdown.signature(data,99.999),'gta,doomsday');
assert.equal(countdown.signature(data,100),'doomsday');
assert.equal(countdown.signature(data,200),'');
assert.deepEqual(countdown.visible({...data,archive:true},0),[]);
assert.deepEqual(countdown.visible({},0),[]);
assert.equal(countdown.signature({countdowns:[{...events[0],enabled:false},events[1]]},0),'doomsday');
assert.deepEqual(countdown.parts(90061,0),[1,1,1,1]);
assert.deepEqual(countdown.parts(100,99.5),[0,0,0,1]);
assert.deepEqual(countdown.parts(100,101),[0,0,0,0]);
assert.deepEqual(countdown.parts(100,100),[0,0,0,0]);
const choose=countdown.createBackgroundSelector(()=>.4);
const first=[choose(events[0]),choose(events[0]),choose(events[0])];
assert.equal(new Set(first).size,3,'Every image appears before repeating');
assert.notEqual(choose(events[0]),first[2],'No repeat at shuffle boundary');
assert.equal(choose({id:'gta',images:['https://example.invalid/pixel','/assets/countdowns/gta-01.jpg']}),'/assets/countdowns/gta-01.jpg');
assert.equal(choose({id:'gta',images:[]}), '');
assert.equal(choose({id:'gta',images:['/assets/countdowns/../../secret.jpg']}), '');
console.log('15 countdown runtime checks passed.');
